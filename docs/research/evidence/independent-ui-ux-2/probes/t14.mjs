import { chromium, shot } from "./lib.mjs"
import { sceneSetup } from "./scene.mjs"
const b = await chromium.launch()
const log = (...a) => console.log(...a)
const fi = (p) => p.evaluate(() => { const a = document.activeElement; return a === document.body ? "BODY" : (a.getAttribute("aria-label") || a.textContent.trim().slice(0,20) || a.tagName) })
const { c, p, scene } = await sceneSetup(b, "Search")
const results = () => scene.getByLabel("Search results").innerText().then(s => s.replace(/\n+/g, " | ").slice(0, 120))
log("initial focus", await fi(p))
await scene.getByRole("button", { name: "Search now" }).click(); await p.waitForTimeout(400)
log("after Search now focus", await fi(p), "cancel visible", await scene.getByRole("button", { name: "Cancel" }).count())
await shot(p, "search-now", { clip: await scene.boundingBox() })
await p.keyboard.type("Al"); await p.waitForTimeout(300)
log("suggestions", await p.getByRole("option").allTextContents())
await p.keyboard.press("ArrowDown"); await p.keyboard.press("Enter"); await p.waitForTimeout(300)
log("after pick value", await scene.getByRole("combobox").inputValue().catch(() => "?"), "results", await results())
await shot(p, "search-picked", { clip: await scene.boundingBox() })
await scene.getByRole("button", { name: "Cancel" }).click().catch(e => log("cancel err", e.message.slice(0, 80))); await p.waitForTimeout(300)
log("after Cancel: value", await scene.getByRole("searchbox").or(scene.getByRole("combobox")).first().inputValue().catch(() => "?"), "focus", await fi(p), "recents", await scene.getByRole("region", { name: "Recent searches" }).innerText().catch(() => "none"))
// Browse (destination)
await scene.getByRole("button", { name: "Search destination" }).click(); await p.waitForTimeout(300)
log("after Browse focus", await fi(p))
// scope via folder sidebar
await scene.getByRole("button", { name: "Show Notes folder" }).click(); await p.waitForTimeout(300)
log("scope Notes results", await results(), "token", await scene.locator('[data-slot="search-field-token"]').allTextContents())
await shot(p, "search-scope-notes", { clip: await scene.boundingBox() })
await scene.getByRole("button", { name: /Remove.*Notes|Remove filter/i }).first().click().catch(e => log("token remove err", e.message.slice(0, 80))); await p.waitForTimeout(300)
log("after token remove: token", await scene.locator('[data-slot="search-field-token"]').count(), "focus", await fi(p))
// local filter
await scene.getByRole("textbox", { name: "Filter this library" }).fill("coast"); await p.waitForTimeout(300)
log("local filter", await results())
await scene.getByRole("textbox", { name: "Filter this library" }).fill("")
await scene.getByRole("textbox", { name: "Search folders" }).fill("pl"); await p.waitForTimeout(300)
log("folder filter", await scene.getByRole("group", { name: "Scope" }).innerText())
await scene.getByRole("textbox", { name: "Search folders" }).fill("")
// empty results
const field = scene.getByRole("combobox", { name: "Search all collections" }).or(scene.getByRole("searchbox", { name: "Search all collections" })).first()
await field.fill("zzzz"); await field.press("Enter"); await p.waitForTimeout(300)
log("empty", await scene.getByRole("status").innerText().catch(() => "none"))
await shot(p, "search-empty", { clip: await scene.boundingBox() })
await scene.getByRole("button", { name: "Clear filters" }).click(); await p.waitForTimeout(300)
log("after clear filters focus", await fi(p), "recents", await scene.getByRole("region", { name: "Recent searches" }).innerText().catch(() => "none"))
// remove recent
await scene.getByRole("button", { name: "Remove recent Coast" }).click(); await p.waitForTimeout(300)
log("after remove recent focus", await fi(p))
await scene.getByRole("button", { name: "Clear", exact: true }).click(); await p.waitForTimeout(300)
log("after Clear all focus", await fi(p), await scene.getByRole("region", { name: "Recent searches" }).innerText().catch(() => "none"))
// Escape in field
await field.fill("lake"); await field.press("Escape"); await p.waitForTimeout(300)
log("after Escape value", await field.inputValue(), "focus", await fi(p))
log("errors", p._errs)
await b.close()
