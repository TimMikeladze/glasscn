import { chromium } from "./lib.mjs"
import { sceneSetup } from "./scene.mjs"
import { probe } from "./contrast.mjs"
const b = await chromium.launch()
const out = []
for (const scheme of ["light", "dark"]) {
  let s = await sceneSetup(b, "Photos", { scheme })
  out.push(await probe(s.p, s.scene.getByText("Sierra Nevada"), `${scheme} photos place`))
  out.push(await probe(s.p, s.scene.getByText("June 14 · 7:24 AM"), `${scheme} photos date`))
  await s.c.close()
  s = await sceneSetup(b, "Music", { scheme })
  out.push(await probe(s.p, s.scene.getByText("A slower morning").last(), `${scheme} music miniplayer`))
  out.push(await probe(s.p, s.scene.getByRole("tab", { name: "New" }).locator("span"), `${scheme} music tab label New`))
  out.push(await probe(s.p, s.scene.getByRole("tab", { name: "Home" }).locator("span"), `${scheme} music tab selected Home`))
  await s.c.close()
  s = await sceneSetup(b, "Maps", { scheme })
  out.push(await probe(s.p, s.scene.getByText("Trails · 2.4 mi"), `${scheme} maps row detail`))
  out.push(await probe(s.p, s.scene.getByText("Nearby"), `${scheme} maps heading`))
  await s.c.close()
  s = await sceneSetup(b, "Controls", { scheme })
  out.push(await probe(s.p, s.scene.getByRole("radio", { name: "Erase" }), `${scheme} controls segment unselected`))
  out.push(await probe(s.p, s.scene.getByText("Mountain study"), `${scheme} controls title pill`))
  await s.c.close()
  s = await sceneSetup(b, "Landmarks", { scheme })
  out.push(await probe(s.p, s.scene.getByText("A still morning beside the water."), `${scheme} landmarks inspector secondary`))
  out.push(await probe(s.p, s.scene.getByText("Saved places"), `${scheme} landmarks sidebar row`))
  out.push(await probe(s.p, s.scene.getByText("Field collection"), `${scheme} landmarks hero eyebrow`))
  await s.c.close()
  s = await sceneSetup(b, "Materials", { scheme })
  out.push(await probe(s.p, s.scene.getByText("Tertiary foreground"), `${scheme} materials tertiary on regular-large`))
  out.push(await probe(s.p, s.scene.getByText("Secondary foreground"), `${scheme} materials secondary on regular-large`))
  out.push(await probe(s.p, s.scene.getByText("Standard material").first(), `${scheme} materials secondary on ultraThin`))
  out.push(await probe(s.p, s.scene.getByText("Bright media"), `${scheme} materials bright media label`))
  out.push(await probe(s.p, s.scene.getByRole("button", { name: "Details" }).first(), `${scheme} materials clear Details on bright`))
  await s.c.close()
  s = await sceneSetup(b, "Notes", { scheme })
  out.push(await probe(s.p, s.scene.getByText(/2026 at/), `${scheme} notes date`))
  await s.c.close()
  s = await sceneSetup(b, "Safari", { scheme })
  out.push(await probe(s.p, s.scene.getByRole("textbox", { name: "Website address" }), `${scheme} safari address`))
  await s.c.close()
}
for (const r of out) console.log(JSON.stringify(r))
await b.close()
